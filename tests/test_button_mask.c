/*
 * Button-mask tests: the regions found in the embedded frame button mask,
 * a few hits against them, and web/button-regions.mjs, the copy the web
 * front end uses. Run with --write <path> to regenerate that file.
 */

#include "ui_button_mask.h"
#include "ui_png.h"

#include "buttons_mask_png_embedded.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static int failures;

#define CHECK(cond) do { \
    if (!(cond)) { \
        fprintf(stderr, "%s:%d: CHECK failed: %s\n", __FILE__, __LINE__, #cond); \
        failures++; \
    } \
} while (0)

static const char *const region_names[UI_BUTTON_REGION_COUNT] = {
    [UI_BUTTON_REGION_DPAD] = "dpad",
    [UI_BUTTON_REGION_ROCKET] = "rocket",
    [UI_BUTTON_REGION_POWER] = "power",
    [UI_BUTTON_REGION_OK] = "ok",
    [UI_BUTTON_REGION_ESC] = "esc",
};

static size_t format_module(const ui_button_mask_t *mask, char *out,
    size_t cap)
{
    size_t n = 0;

    n += (size_t)snprintf(out + n, cap - n,
        "// Generated by tests/test_button_mask.c --write from\n"
        "// src/ui/assets/buttons_dpad_bw_mask.png; do not edit.\n"
        "// The desktop front end finds the same regions at startup\n"
        "// (src/ui_button_mask.c).\n"
        "export const BUTTON_MASK_SIZE = { width: %u, height: %u };\n"
        "export const BUTTON_REGIONS = {\n",
        mask->width, mask->height);
    for (int i = UI_BUTTON_REGION_DPAD; i < UI_BUTTON_REGION_COUNT; i++) {
        const ui_button_region_t *r = &mask->regions[i];

        n += (size_t)snprintf(out + n, cap - n,
            "  %s: { minX: %u, minY: %u, maxX: %u, maxY: %u, "
            "cx: %.6f, cy: %.6f },\n",
            region_names[i], r->min_x, r->min_y, r->max_x, r->max_y,
            r->cx, r->cy);
    }
    n += (size_t)snprintf(out + n, cap - n, "};\n");
    return n;
}

static char *read_file(const char *path)
{
    FILE *f = fopen(path, "rb");
    long len;
    char *buf;

    if (!f)
        return NULL;
    fseek(f, 0, SEEK_END);
    len = ftell(f);
    fseek(f, 0, SEEK_SET);
    buf = malloc((size_t)len + 1);
    if (buf && fread(buf, 1, (size_t)len, f) == (size_t)len) {
        buf[len] = '\0';
    } else {
        free(buf);
        buf = NULL;
    }
    fclose(f);
    return buf;
}

static void expect_hit(const ui_button_mask_t *mask, double x, double y,
    uint8_t set1, uint8_t set2)
{
    uint8_t got1 = 0, got2 = 0;

    CHECK(ui_button_mask_hit(mask, x, y, &got1, &got2));
    CHECK(got1 == set1 && got2 == set2);
}

int main(int argc, char **argv)
{
    ui_button_mask_t mask = { 0 };
    uint8_t *rgba = NULL;
    uint32_t w = 0, h = 0;
    char text[4096];
    char *file;
    const ui_button_region_t *dpad;

    if (!ui_load_png_rgba(be300_buttons_mask_png,
        (size_t)be300_buttons_mask_png_len, &rgba, &w, &h) ||
        !ui_button_mask_build(&mask, rgba, w, h)) {
        fprintf(stderr, "cannot analyse the embedded button mask\n");
        return 1;
    }
    free(rgba);
    format_module(&mask, text, sizeof(text));

    if (argc == 3 && strcmp(argv[1], "--write") == 0) {
        FILE *f = fopen(argv[2], "w");

        if (!f || fputs(text, f) < 0 || fclose(f) != 0) {
            fprintf(stderr, "cannot write %s\n", argv[2]);
            return 1;
        }
        return 0;
    }

    /* The D-pad's centre is OK, its far edges the directions; the side
     * buttons answer at their own centres. */
    dpad = &mask.regions[UI_BUTTON_REGION_DPAD];
    expect_hit(&mask, dpad->cx, dpad->cy, 0x04, 0);
    expect_hit(&mask, dpad->cx, dpad->min_y + 6, 0x10, 0);
    expect_hit(&mask, dpad->cx, dpad->max_y - 6, 0x20, 0);
    expect_hit(&mask, mask.regions[UI_BUTTON_REGION_ROCKET].cx,
        mask.regions[UI_BUTTON_REGION_ROCKET].cy, 0, 0x10);
    expect_hit(&mask, mask.regions[UI_BUTTON_REGION_ESC].cx,
        mask.regions[UI_BUTTON_REGION_ESC].cy, 0x08, 0);

    file = read_file(BE300_SOURCE_DIR "/web/button-regions.mjs");
    if (!file || strcmp(file, text) != 0) {
        fprintf(stderr, "web/button-regions.mjs is stale; regenerate it with\n"
            "  test_button_mask --write web/button-regions.mjs\n"
            "expected:\n%s", text);
        failures++;
    }
    free(file);
    ui_button_mask_free(&mask);

    if (failures) {
        fprintf(stderr, "%d failure(s)\n", failures);
        return 1;
    }
    printf("button mask: ok\n");
    return 0;
}
