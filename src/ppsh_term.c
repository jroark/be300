/*
 *  ppsh_term.c — SDL2 text-mode console for the PPSH debug shell.
 *
 *  Opens a second SDL window rendering an 80x25 character grid with an
 *  embedded 8x8 bitmap font. PPSH output from the guest is fed in via
 *  ppsh_term_write(); keystrokes forwarded in via ppsh_term_handle_sdl_event()
 *  are queued and drained by ppsh_term_read().
 *
 *  This file has no dependency on any other BE-300 state — the machine
 *  layer owns the ppsh_term_t pointer and wires it to the PPSH device.
 */

