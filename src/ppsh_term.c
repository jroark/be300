struct ppsh_term {
    SDL_Window   *window;
    SDL_Renderer *renderer;
    SDL_Texture  *texture;
    uint32_t      window_id;
    uint32_t     *pixels;       /* TERM_COLS*GLYPH_W x TERM_ROWS*GLYPH_H ARGB */

    uint8_t  grid[TERM_ROWS][TERM_COLS];
    int      cursor_row;
    int      cursor_col;
    bool     dirty;

    uint8_t  in_ring[IN_RING_CAP];
    size_t   in_head;
    size_t   in_tail;
    size_t   in_count;

    uint32_t last_render_tick;
    uint32_t blink_origin_tick;
    bool     cursor_visible;
};

#define FRAME_INTERVAL_MS 33
#define CURSOR_BLINK_MS   500

static void term_scroll_up(ppsh_term_t *t)
{
    memmove(&t->grid[0][0], &t->grid[1][0],
        (TERM_ROWS - 1) * TERM_COLS);
    memset(&t->grid[TERM_ROWS - 1][0], ' ', TERM_COLS);
}

static void term_newline(ppsh_term_t *t)
{
    t->cursor_row++;
    if (t->cursor_row >= TERM_ROWS) {
        term_scroll_up(t);
        t->cursor_row = TERM_ROWS - 1;
    }
}

static void term_putc(ppsh_term_t *t, uint8_t ch)
{
    switch (ch) {
    case '\r':
        t->cursor_col = 0;
        return;
    case '\n':
        term_newline(t);
        return;
    case '\b':
        if (t->cursor_col > 0) {
            t->cursor_col--;
            t->grid[t->cursor_row][t->cursor_col] = ' ';
        }
        return;
    case '\t': {
        int next = (t->cursor_col + 8) & ~7;
        while (t->cursor_col < next && t->cursor_col < TERM_COLS)
            t->grid[t->cursor_row][t->cursor_col++] = ' ';
        return;
    }
    default:
        break;
    }

    if (ch < 0x20 || ch > 0x7E)
        ch = '?';

    if (t->cursor_col >= TERM_COLS) {
        t->cursor_col = 0;
        term_newline(t);
    }
    t->grid[t->cursor_row][t->cursor_col++] = ch;
}

static void draw_cell(ppsh_term_t *t, int row, int col, uint8_t ch,
    bool inverse)
{
    const uint8_t *bm;
    if (ch < 0x20 || ch > 0x7F)
        bm = font8x8[0];
    else
        bm = font8x8[ch - 0x20];

    uint32_t fg = 0xFFC0C0C0u;
    uint32_t bg = 0xFF000000u;
    if (inverse) { uint32_t tmp = fg; fg = bg; bg = tmp; }

    int stride = TERM_COLS * GLYPH_W;
    uint32_t *base = &t->pixels[(row * GLYPH_H) * stride + col * GLYPH_W];
    for (int y = 0; y < GLYPH_H; y++) {
        uint8_t bits = bm[y];
        for (int x = 0; x < GLYPH_W; x++)
            base[y * stride + x] = (bits & (1u << x)) ? fg : bg;
    }
}

static void redraw_all(ppsh_term_t *t)
{
    for (int r = 0; r < TERM_ROWS; r++)
        for (int c = 0; c < TERM_COLS; c++)
            draw_cell(t, r, c, t->grid[r][c], false);

    if (t->cursor_visible
        && t->cursor_row >= 0 && t->cursor_row < TERM_ROWS
        && t->cursor_col >= 0 && t->cursor_col < TERM_COLS) {
        draw_cell(t, t->cursor_row, t->cursor_col,
            t->grid[t->cursor_row][t->cursor_col], true);
    }
}

ppsh_term_t *ppsh_term_create(const char *title)
{
    if (SDL_WasInit(SDL_INIT_VIDEO) == 0) {
        if (SDL_InitSubSystem(SDL_INIT_VIDEO) != 0) {
            fprintf(stderr,
                "[PPSH_TERM] SDL_InitSubSystem(VIDEO) failed: %s\n",
                SDL_GetError());
            return NULL;
        }
    }

    ppsh_term_t *t = calloc(1, sizeof(*t));
    if (!t)
        return NULL;

    int win_w = TERM_COLS * GLYPH_W * WIN_SCALE;
    int win_h = TERM_ROWS * GLYPH_H * WIN_SCALE;
    t->window = SDL_CreateWindow(
        title ? title : "BE-300 PPSH",
        SDL_WINDOWPOS_CENTERED, SDL_WINDOWPOS_CENTERED,
        win_w, win_h, 0);
    if (!t->window) {
        fprintf(stderr, "[PPSH_TERM] SDL_CreateWindow failed: %s\n",
            SDL_GetError());
        free(t);
        return NULL;
    }
    t->window_id = SDL_GetWindowID(t->window);

    t->renderer = SDL_CreateRenderer(t->window, -1,
        SDL_RENDERER_ACCELERATED);
    if (!t->renderer)
        t->renderer = SDL_CreateRenderer(t->window, -1,
            SDL_RENDERER_SOFTWARE);
    if (!t->renderer) {
        fprintf(stderr, "[PPSH_TERM] SDL_CreateRenderer failed: %s\n",
            SDL_GetError());
        SDL_DestroyWindow(t->window);
        free(t);
        return NULL;
    }
    SDL_RenderSetLogicalSize(t->renderer,
        TERM_COLS * GLYPH_W, TERM_ROWS * GLYPH_H);

    t->texture = SDL_CreateTexture(t->renderer,
        SDL_PIXELFORMAT_ARGB8888,
        SDL_TEXTUREACCESS_STREAMING,
        TERM_COLS * GLYPH_W, TERM_ROWS * GLYPH_H);
    if (!t->texture) {
        fprintf(stderr, "[PPSH_TERM] SDL_CreateTexture failed: %s\n",
            SDL_GetError());
        SDL_DestroyRenderer(t->renderer);
        SDL_DestroyWindow(t->window);
        free(t);
        return NULL;
    }

    size_t px_count = (size_t)TERM_COLS * GLYPH_W
                    * (size_t)TERM_ROWS * GLYPH_H;
    t->pixels = calloc(px_count, sizeof(uint32_t));
    if (!t->pixels) {
        SDL_DestroyTexture(t->texture);
        SDL_DestroyRenderer(t->renderer);
        SDL_DestroyWindow(t->window);
        free(t);
        return NULL;
    }

    memset(t->grid, ' ', sizeof(t->grid));
    t->cursor_row = 0;
    t->cursor_col = 0;
    t->cursor_visible = true;
    t->blink_origin_tick = SDL_GetTicks();
    t->last_render_tick = 0;
    t->dirty = true;

    SDL_StartTextInput();

    fprintf(stderr,
        "[PPSH_TERM] opened %dx%d console window (id=%u)\n",
        TERM_COLS, TERM_ROWS, t->window_id);
    return t;
}

void ppsh_term_destroy(ppsh_term_t *t)
{
    if (!t)
        return;
    if (t->texture)
        SDL_DestroyTexture(t->texture);
    if (t->renderer)
        SDL_DestroyRenderer(t->renderer);
    if (t->window)
        SDL_DestroyWindow(t->window);
    free(t->pixels);
    free(t);
}

void ppsh_term_write(ppsh_term_t *t, const uint8_t *buf, size_t n)
{
    if (!t || !buf)
        return;
    for (size_t i = 0; i < n; i++)
        term_putc(t, buf[i]);
    t->dirty = true;
}

static void in_push(ppsh_term_t *t, uint8_t b)
{
    if (t->in_count >= IN_RING_CAP)
        return;
    t->in_ring[t->in_head] = b;
    t->in_head = (t->in_head + 1u) % IN_RING_CAP;
    t->in_count++;
}

size_t ppsh_term_read(ppsh_term_t *t, uint8_t *buf, size_t cap)
{
    if (!t || !buf)
        return 0;
    size_t n = 0;
    while (n < cap && t->in_count > 0) {
        buf[n++] = t->in_ring[t->in_tail];
        t->in_tail = (t->in_tail + 1u) % IN_RING_CAP;
        t->in_count--;
    }
    return n;
}

uint32_t ppsh_term_window_id(ppsh_term_t *t)
{
    return t ? t->window_id : 0u;
}

void ppsh_term_handle_sdl_event(ppsh_term_t *t, const void *sdl_event)
{
    if (!t || !sdl_event)
        return;
    const SDL_Event *ev = (const SDL_Event *)sdl_event;

    switch (ev->type) {
    case SDL_TEXTINPUT:
        if (ev->text.windowID != t->window_id)
            return;
        for (const char *p = ev->text.text; *p; p++) {
            uint8_t b = (uint8_t)*p;
            if (b >= 0x20 && b <= 0x7E)
                in_push(t, b);
        }
        break;

    case SDL_KEYDOWN: {
        if (ev->key.windowID != t->window_id)
            return;
        SDL_Keycode k = ev->key.keysym.sym;
        uint16_t mod = ev->key.keysym.mod;
        if (mod & KMOD_CTRL) {
            if (k >= SDLK_a && k <= SDLK_z) {
                in_push(t, (uint8_t)(k - SDLK_a + 1));
                return;
            }
        }
        switch (k) {
        case SDLK_RETURN:
        case SDLK_KP_ENTER:
            in_push(t, '\r');
            break;
        case SDLK_BACKSPACE:
            in_push(t, 0x08);
            break;
        case SDLK_TAB:
            in_push(t, '\t');
            break;
        case SDLK_ESCAPE:
            in_push(t, 0x1B);
            break;
        default:
            break;
        }
        break;
    }

    case SDL_WINDOWEVENT:
        if (ev->window.windowID != t->window_id)
            return;
        if (ev->window.event == SDL_WINDOWEVENT_EXPOSED
            || ev->window.event == SDL_WINDOWEVENT_SHOWN)
            t->dirty = true;
        break;

    default:
        break;
    }
}

void ppsh_term_render(ppsh_term_t *t)
{
    if (!t || !t->window)
        return;

    uint32_t now = SDL_GetTicks();
    if (now - t->last_render_tick < FRAME_INTERVAL_MS)
        return;
    t->last_render_tick = now;

    bool cursor_now = ((now - t->blink_origin_tick) / CURSOR_BLINK_MS) & 1u
        ? false : true;
    if (cursor_now != t->cursor_visible) {
        t->cursor_visible = cursor_now;
        t->dirty = true;
    }

    if (t->dirty) {
        redraw_all(t);
        SDL_UpdateTexture(t->texture, NULL, t->pixels,
            TERM_COLS * GLYPH_W * (int)sizeof(uint32_t));
        t->dirty = false;
    }

    SDL_RenderClear(t->renderer);
    SDL_RenderCopy(t->renderer, t->texture, NULL, NULL);
    SDL_RenderPresent(t->renderer);
}

